function esc(s: string): string {
    return s
        .replace(/&/g, "&amp;")
        .replace(/</g, "&lt;")
        .replace(/>/g, "&gt;")
        .replace(/"/g, "&quot;")
        .replace(/'/g, "&apos;");
}

/** amount > 0 — к белому, amount < 0 — к чёрному */
function shade(hex: string, amount: number): string {
    const n = Number.parseInt(hex.slice(1), 16);
    const target = amount > 0 ? 255 : 0;
    const t = Math.abs(amount);
    const channel = (shift: number) => {
        const c = (n >> shift) & 0xff;
        return Math.round(c + (target - c) * t)
            .toString(16)
            .padStart(2, "0");
    };
    return `#${channel(16)}${channel(8)}${channel(0)}`;
}

function wrap(text: string, maxChars: number): string[] {
    const lines: string[] = [];
    let line = "";
    for (const word of text.split(" ")) {
        const next = line ? `${line} ${word}` : word;
        if (next.length > maxChars && line) {
            lines.push(line);
            line = word;
        } else {
            line = next;
        }
    }
    if (line) lines.push(line);
    return lines;
}

function makeCover(b: SeedBook): string {
    const w = b.widthPx;
    const h = Math.round(w * 1.5);
    const cx = w / 2;
    const ink = b.spineTextColor;
    const m1 = Math.round(w * 0.05);
    const m2 = Math.round(w * 0.11);
    const titleSize = Math.max(13, Math.round(w * 0.1));
    const authorSize = Math.round(titleSize * 0.62);
    const maxChars = Math.max(
        8,
        Math.floor((w - m2 * 2 - 8) / (titleSize * 0.52)),
    );
    const lines = wrap(b.title, maxChars);
    const lineH = Math.round(titleSize * 1.3);
    const titleTop = Math.round(h * 0.4 - ((lines.length - 1) * lineH) / 2);
    const titleText = lines
        .map(
            (line, i) =>
                `<text x="${cx}" y="${titleTop + i * lineH}" text-anchor="middle" font-family="Georgia, 'Times New Roman', serif" font-size="${titleSize}" font-weight="bold" fill="${ink}">${esc(line)}</text>`,
        )
        .join("");
    // арочная внутренняя рамка
    const x1 = m2;
    const x2 = w - m2;
    const y2 = h - m2;
    const spring = m2 + Math.round(w * 0.18);
    const arch = `M ${x1} ${y2} L ${x1} ${spring} Q ${x1} ${m2} ${cx} ${m2} Q ${x2} ${m2} ${x2} ${spring} L ${x2} ${y2} Z`;
    const fl = Math.round(h * 0.55);
    const d = Math.max(3, Math.round(w * 0.022));
    const gap = Math.round(w * 0.05);
    const arm = Math.round(w * 0.14);
    return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}">
<defs>
<linearGradient id="bg" x1="0" y1="0" x2="0" y2="1">
<stop offset="0" stop-color="${shade(b.spineColor, 0.28)}"/>
<stop offset="1" stop-color="${shade(b.spineColor, -0.12)}"/>
</linearGradient>
</defs>
<rect width="${w}" height="${h}" fill="url(#bg)"/>
<rect x="${m1}" y="${m1}" width="${w - m1 * 2}" height="${h - m1 * 2}" fill="none" stroke="${ink}" stroke-width="1.5" opacity="0.8"/>
<path d="${arch}" fill="none" stroke="${ink}" stroke-width="1" opacity="0.55"/>
${titleText}
<g stroke="${ink}" stroke-width="1" opacity="0.7">
<line x1="${cx - gap - arm}" y1="${fl}" x2="${cx - gap}" y2="${fl}"/>
<line x1="${cx + gap}" y1="${fl}" x2="${cx + gap + arm}" y2="${fl}"/>
</g>
<rect x="${cx - d}" y="${fl - d}" width="${d * 2}" height="${d * 2}" fill="${ink}" opacity="0.85" transform="rotate(45 ${cx} ${fl})"/>
<text x="${cx}" y="${Math.round(h * 0.63)}" text-anchor="middle" font-family="Georgia, 'Times New Roman', serif" font-size="${authorSize}" font-style="italic" fill="${ink}" opacity="0.9">${esc(b.author)}</text>
</svg>`;
}

export async function seed(pool: Pool): Promise<void> {
    for (const b of BOOKS) {
        await pool.query(
            `INSERT INTO books (slug, title, author, synopsis, review,
                rating, pages, width_px, height_px, spine_color,
                spine_text_color, cover_image, cover_mime, date_read)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
            [
                b.slug,
                b.title,
                b.author,
                b.synopsis,
                b.review,
                b.rating,
                b.pages,
                b.widthPx,
                b.heightPx,
                b.spineColor,
                b.spineTextColor,
                Buffer.from(makeCover(b), "utf8"),
                "image/svg+xml",
                b.dateRead,
            ],
        );
    }
}
